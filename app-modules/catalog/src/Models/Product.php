<?php

declare(strict_types=1);

namespace Vevey\Catalog\Models;

use App\Casts\MoneyCast;
use Brick\Money\Money;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Attributes\Hidden;
use Illuminate\Database\Eloquent\Attributes\Scope;
use Illuminate\Database\Eloquent\Attributes\Table;
use Illuminate\Database\Eloquent\Attributes\UseFactory;
use Illuminate\Database\Eloquent\Attributes\UsePolicy;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Casts\Attribute as AttributeCast;
use Illuminate\Database\Eloquent\Collection;
use Illuminate\Database\Eloquent\Concerns\HasUuids;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsToMany;
use Illuminate\Database\Eloquent\SoftDeletes;
use Illuminate\Support\Carbon;
use Override;
use Spatie\Image\Enums\Fit;
use Spatie\MediaLibrary\HasMedia;
use Spatie\MediaLibrary\InteractsWithMedia;
use Spatie\MediaLibrary\MediaCollections\Models\Media;
use Vevey\Catalog\Database\Factories\ProductFactory;
use Vevey\Catalog\Policies\ProductPolicy;

/**
 * Every color is its own product (flat catalog, ADR 6). Prices are integer-cents columns read as BRL Money (ADR 1).
 * On Postgres the table also has `search_vector`, a stored generated tsvector of name and description used by search().
 *
 * @property string $id
 * @property string $sku
 * @property string|null $barcode
 * @property string $name
 * @property string $slug
 * @property string|null $description
 * @property Money $price_cents
 * @property Money|null $promo_price_cents
 * @property bool $is_active
 * @property Carbon|null $created_at
 * @property Carbon|null $updated_at
 * @property Carbon|null $deleted_at
 * @property-read Money $sale_price
 * @property-read Collection<int, Category> $categories
 * @property-read Collection<int, AttributeValue> $attributeValues
 * @property-read Collection<int, Media> $media
 */
#[UseFactory(ProductFactory::class)]
#[UsePolicy(ProductPolicy::class)]
#[Fillable(['sku', 'barcode', 'name', 'slug', 'description', 'price_cents', 'promo_price_cents', 'is_active'])]
#[Hidden(['search_vector'])]
#[Table(name: 'products')]
final class Product extends Model implements HasMedia
{
    /** @use HasFactory<ProductFactory> */
    use HasFactory;

    use HasUuids;
    use InteractsWithMedia;
    use SoftDeletes;

    public const string IMAGES_COLLECTION = 'images';

    public const string THUMB_CONVERSION = 'thumb';

    public const string LARGE_CONVERSION = 'large';

    /**
     * @return BelongsToMany<Category, $this>
     */
    public function categories(): BelongsToMany
    {
        return $this->belongsToMany(Category::class);
    }

    /**
     * @return BelongsToMany<AttributeValue, $this>
     */
    public function attributeValues(): BelongsToMany
    {
        return $this->belongsToMany(AttributeValue::class);
    }

    /**
     * `search_vector` is generated by Postgres and cannot be written, so a copy never carries it.
     *
     * @param  array<int, string>|null  $except
     */
    #[Override]
    public function replicate(?array $except = null): static
    {
        return parent::replicate([...$except ?? [], 'search_vector']);
    }

    public function registerMediaCollections(): void
    {
        $this->addMediaCollection(self::IMAGES_COLLECTION)
            ->acceptsMimeTypes(['image/jpeg', 'image/png', 'image/webp']);
    }

    public function registerMediaConversions(?Media $media = null): void
    {
        $this->addMediaConversion(self::THUMB_CONVERSION)
            ->fit(Fit::Crop, 400, 400)
            ->format('webp');

        $this->addMediaConversion(self::LARGE_CONVERSION)
            ->fit(Fit::Contain, 900, 900)
            ->format('webp');
    }

    /**
     * The price charged now: the promotional price when there is one, otherwise the regular price.
     *
     * @return AttributeCast<Money, never>
     */
    protected function salePrice(): AttributeCast
    {
        return AttributeCast::get(fn (): Money => $this->promo_price_cents ?? $this->price_cents);
    }

    /**
     * @param  Builder<Product>  $query
     */
    #[Scope]
    protected function active(Builder $query): void
    {
        $query->where('is_active', true);
    }

    /**
     * Name and description by full text in Portuguese (ADR 6: never ILIKE), or SKU and barcode exactly.
     * Off Postgres (the SQLite test database) the full text part falls back to a LIKE on the name.
     *
     * @param  Builder<Product>  $query
     */
    #[Scope]
    protected function search(Builder $query, string $term): void
    {
        $term = mb_trim($term);

        if ($term === '') {
            return;
        }

        $query->where(function (Builder $query) use ($term): void {
            $query->whereIn('sku', array_unique([$term, mb_strtoupper($term)]))
                ->orWhere('barcode', $term);

            if ($query->getModel()->getConnection()->getDriverName() === 'pgsql') {
                $query->orWhereFullText('search_vector', $term, ['language' => 'portuguese', 'vector' => true, 'mode' => 'websearch']);
            } else {
                $query->orWhere('name', 'like', '%' . $term . '%');
            }
        });
    }

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'price_cents' => MoneyCast::class,
            'promo_price_cents' => MoneyCast::class,
            'is_active' => 'boolean',
        ];
    }
}
